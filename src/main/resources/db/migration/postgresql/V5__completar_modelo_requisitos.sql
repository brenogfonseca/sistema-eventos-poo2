-- Estado do evento e modalidade para distinguir rascunhos, publicações e eventos encerrados.
ALTER TABLE eventos
    ADD COLUMN modalidade TEXT NOT NULL DEFAULT 'PRESENCIAL'
        CHECK (modalidade IN ('PRESENCIAL', 'ONLINE', 'HIBRIDO')),
    ADD COLUMN status TEXT NOT NULL DEFAULT 'RASCUNHO'
        CHECK (status IN ('RASCUNHO', 'PUBLICADO', 'CANCELADO', 'ENCERRADO')),
    ADD COLUMN fuso_horario TEXT NOT NULL DEFAULT 'America/Sao_Paulo';

ALTER TABLE eventos
    ADD CONSTRAINT ck_evento_frequencia_certificado
        CHECK (frequencia_minima IN (50, 75, 100));

-- Categorias e trilhas pertencem a um evento e podem ser usadas na programação pública.
CREATE TABLE categorias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id INTEGER NOT NULL REFERENCES eventos(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    CONSTRAINT uq_categoria_evento_nome UNIQUE (evento_id, nome)
);

CREATE TABLE trilhas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id INTEGER NOT NULL REFERENCES eventos(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    descricao TEXT,
    CONSTRAINT uq_trilha_evento_nome UNIQUE (evento_id, nome)
);

ALTER TABLE atividades
    ADD COLUMN descricao TEXT,
    ADD COLUMN categoria_id INTEGER REFERENCES categorias(id) ON DELETE SET NULL,
    ADD COLUMN trilha_evento_id INTEGER REFERENCES trilhas(id) ON DELETE SET NULL;

-- Pessoas da programação não precisam ter conta no sistema.
CREATE TABLE pessoas_programacao (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    organizacao TEXT,
    biografia TEXT,
    foto_url TEXT
);

CREATE TABLE atividade_pessoas (
    atividade_id INTEGER NOT NULL REFERENCES atividades(id) ON DELETE CASCADE,
    pessoa_id INTEGER NOT NULL REFERENCES pessoas_programacao(id) ON DELETE CASCADE,
    papel TEXT NOT NULL CHECK (papel IN ('PALESTRANTE', 'APRESENTADOR', 'RESPONSAVEL')),
    PRIMARY KEY (atividade_id, pessoa_id, papel)
);

ALTER TABLE questionarios
    ADD COLUMN anonimo INTEGER NOT NULL DEFAULT 0 CHECK (anonimo IN (0, 1)),
    ADD COLUMN publicado INTEGER NOT NULL DEFAULT 0 CHECK (publicado IN (0, 1));

ALTER TABLE questoes
    ADD COLUMN opcoes TEXT,
    ADD COLUMN escala_minima INTEGER,
    ADD COLUMN escala_maxima INTEGER;

-- Impede avaliações duplicadas por pergunta, inclusive em submissões repetidas.
CREATE UNIQUE INDEX uq_resposta_questao_usuario
    ON respostas(questao_id, usuario_id);

-- Garante uma escolha ativa por participante/atividade mesmo com requisições concorrentes.
CREATE UNIQUE INDEX uq_inscricao_ativa_evento_atividade
    ON inscricoes(inscricao_evento_id, atividade_id)
    WHERE cancelada = 0;

CREATE UNIQUE INDEX uq_usuario_email_normalizado ON usuarios (LOWER(email));
CREATE INDEX idx_eventos_status_inicio ON eventos(status, inicio);
CREATE INDEX idx_atividades_evento_data_hora ON atividades(evento_id, data, hora_inicio);
CREATE INDEX idx_inscricoes_evento_atividade ON inscricoes(inscricao_evento_id, atividade_id);
CREATE INDEX idx_questionarios_publicados ON questionarios(publicado, atividade_id);
CREATE UNIQUE INDEX uq_categoria_evento_nome_normalizado ON categorias(evento_id, LOWER(nome));
CREATE UNIQUE INDEX uq_trilha_evento_nome_normalizado ON trilhas(evento_id, LOWER(nome));

-- Certificados emitidos são registros históricos, independentes do recálculo futuro da presença.
CREATE TABLE certificados (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id INTEGER NOT NULL REFERENCES eventos(id) ON DELETE RESTRICT,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    tipo TEXT NOT NULL CHECK (tipo IN ('PARTICIPANTE', 'PALESTRANTE', 'APRESENTADOR')),
    carga_horaria_minutos INTEGER NOT NULL CHECK (carga_horaria_minutos >= 0),
    emitido_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    arquivo_nome TEXT NOT NULL,
    CONSTRAINT uq_certificado_evento_usuario_tipo UNIQUE (evento_id, usuario_id, tipo)
);
